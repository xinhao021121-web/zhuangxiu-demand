const workbook = Workbook.create();
const sheet = workbook.worksheets.add("字段总表");
sheet.showGridLines = false;

const headers = ["字段ID", "分区", "分组", "字段名", "控件类型", "选项 / 单位", "是否必填", "发现规则触发（纯规则）", "来源", "备注"];
const HEADER_ROW = 4;
const FIRST_DATA_ROW = 5;
const lastDataRow = FIRST_DATA_ROW + rows.length - 1;
const LAST_COL = "J";

sheet.getRange(`A2:${LAST_COL}2`).merge();
sheet.getRange("A2").values = [["装修需求采集表 · 字段清单 V1（房主端 Web 填写页 · 纯规则发现）"]];
sheet.getRange(`A2:${LAST_COL}2`).format.font = { name: FONT, size: 14, bold: true, color: "#1F3864" };
sheet.getRange(`A2:${LAST_COL}2`).format.rowHeightPx = 26;
sheet.getRange(`A2:${LAST_COL}2`).format.borders = { bottom: { style: "thin", color: "#B7C0CC" } };

sheet.getRange(`A${HEADER_ROW}:${LAST_COL}${HEADER_ROW}`).values = [headers];
sheet.getRange(`A${HEADER_ROW}:${LAST_COL}${HEADER_ROW}`).format = {
  fill: "#1F3864",
  font: { name: FONT, size: 10, bold: true, color: "#FFFFFF" },
  verticalAlignment: "center",
  horizontalAlignment: "center",
  rowHeightPx: 26,
  borders: {
    insideVertical: { style: "thin", color: "#FFFFFF" },
    bottom: { style: "medium", color: "#1F3864" },
  },
};

sheet.getRange(`A${FIRST_DATA_ROW}:${LAST_COL}${lastDataRow}`).values = rows;
const body = sheet.getRange(`A${FIRST_DATA_ROW}:${LAST_COL}${lastDataRow}`);
body.format = {
  font: { name: FONT, size: 10, color: "#16181C" },
  verticalAlignment: "center",
  borders: { insideHorizontal: { style: "thin", color: "#E8EBEF" } },
};

sheet.getRange(`F${FIRST_DATA_ROW}:F${lastDataRow}`).format.wrapText = true;
sheet.getRange(`H${FIRST_DATA_ROW}:H${lastDataRow}`).format.wrapText = true;
body.format.autofitRows();
sheet.getRange(`D${FIRST_DATA_ROW}:E${lastDataRow}`).format.horizontalAlignment = "left";
sheet.getRange(`G${FIRST_DATA_ROW}:G${lastDataRow}`).format.horizontalAlignment = "center";
sheet.getRange(`I${FIRST_DATA_ROW}:I${lastDataRow}`).format.horizontalAlignment = "center";

// 分区切换处加较强的分隔线
for (let i = 1; i < rows.length; i += 1) {
  if (rows[i][1] !== rows[i - 1][1]) {
    const r = FIRST_DATA_ROW + i;
    sheet.getRange(`A${r}:${LAST_COL}${r}`).format.borders = { top: { style: "medium", color: "#B7C0CC" } };
  }
}

// 列宽
const widths = [16, 14, 12, 26, 11, 52, 10, 34, 9, 26];
widths.forEach((w, idx) => {
  const col = String.fromCharCode(65 + idx);
  sheet.getRange(`${col}${HEADER_ROW}:${col}${lastDataRow}`).format.columnWidth = w;
});

sheet.freezePanes.freezeRows(HEADER_ROW);
sheet.freezePanes.freezeColumns(2);

// 参考来源区
const legendTitleRow = lastDataRow + 2;
sheet.getRange(`A${legendTitleRow}`).values = [["参考来源"]];
sheet.getRange(`A${legendTitleRow}`).format.font = { name: FONT, size: 11, bold: true, color: "#1F3864" };
const sourceStart = legendTitleRow + 1;
sheet.getRange(`A${sourceStart}:A${sourceStart + sources.length - 1}`).values = sources.map((s) => [s[0]]);
sheet.getRange(`B${sourceStart}:B${sourceStart + sources.length - 1}`).values = sources.map((s) => [s[1]]);
sheet.getRange(`H${sourceStart}:H${sourceStart + sources.length - 1}`).values = sources.map((s) => [s[2]]);
const legend = sheet.getRange(`A${sourceStart}:J${sourceStart + sources.length - 1}`);
legend.format.font = { name: FONT, size: 9, color: "#5A5F66" };
legend.format.verticalAlignment = "center";
sheet.getRange(`A${sourceStart}:A${sourceStart + sources.length - 1}`).format.horizontalAlignment = "center";
sheet.getRange(`H${sourceStart}:H${sourceStart + sources.length - 1}`).format.wrapText = false;

workbook.recalculate();

await fs.mkdir(outputDir, { recursive: true });
const preview = await workbook.render({ sheetName: "字段总表", autoCrop: "all", scale: 1, format: "png" });
await fs.writeFile(`${outputDir}/fields-preview.png`, new Uint8Array(await preview.arrayBuffer()));

